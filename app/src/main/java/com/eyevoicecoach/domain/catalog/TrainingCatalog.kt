    private fun createProgram(
        id: String,
        title: String,
        description: String,
        stageSeeds: List<Pair<String, List<String>>>,
        eyeFocus: String,
        voiceFocus: String,
        startingTip: Int,
    ): TrainingProgram {
        var dayNumber = 0
        val stages = stageSeeds.mapIndexed { stageIndex, (stageTitle, titles) ->
            val days = titles.map { dayTitle ->
                dayNumber += 1
                ProgramDay(
                    number = dayNumber,
                    stageTitle = stageTitle,
                    title = dayTitle,
                    studyText = "في هذه الجلسة ركّز على «$dayTitle». خذ دقيقتين للتحضير، ثم نفّذ التمرين بهدوء وكرر المحاولة بعد الاستماع إلى تسجيلك.",
                    eyeCue = "العين: حافظ على $eyeFocus، وانقل نظرك بسلاسة عند الانتقال بين الأفكار.",
                    bodyCue = "الجسد: ثبّت القدمين، أرخِ الكتفين، واجعل الإيماءة خادمة للمعنى لا بديلاً عنه.",
                    voiceCue = "الصوت: طبّق $voiceFocus، وخذ نفساً صغيراً قبل الجملة الأهم.",
                    recordingChallenge = "سجّل تطبيقاً مدته من ٤٥ إلى ٦٠ ثانية بعنوان «$dayTitle»، ثم قيّم وضوحك وثقتك ووقفاتك.",
                    tipId = ((startingTip + dayNumber - 2) % 18) + 1,
                )
            }
            ProgramStage(stageTitle, "المرحلة ${listOf("١", "٢", "٣")[stageIndex]}: بناء مهارة قابلة للملاحظة قبل الانتقال إلى التالية.", days)
        }
        return TrainingProgram(id, title, dayNumber, description, stages)
    }

    private fun situation(id: String, title: String, script: String, body: String, voice: String, challenge: String, mistakes: String, tipId: Int) =
        RealWorldSituation(id, title, script, body, voice, challenge, mistakes, tipId)

    private fun drill(id: String, category: String, title: String, instruction: String, challenge: String, tipId: Int, safety: String? = null) =
        SpecializedDrill(id, category, title, instruction, challenge, safety, tipId)
