package com.eyevoicecoach.domain.catalog

/** A ready-made multi-day coaching program available without an internet connection. */
data class TrainingProgram(
    val id: String,
    val title: String,
    val durationDays: Int,
    val description: String,
    val stages: List<ProgramStage>,
) {
    /** All daily sessions flattened in their intended order. */
    val days: List<ProgramDay> get() = stages.flatMap(ProgramStage::days)
}

/** A named phase within a ready-made program. */
data class ProgramStage(val title: String, val description: String, val days: List<ProgramDay>)

/** One complete practice session in a program. */
data class ProgramDay(
    val number: Int,
    val stageTitle: String,
    val title: String,
    val studyText: String,
    val eyeCue: String,
    val bodyCue: String,
    val voiceCue: String,
    val recordingChallenge: String,
    val tipId: Int,
)

/** A real-world communication scenario with coordinated eye, body and voice coaching. */
data class RealWorldSituation(
    val id: String,
    val title: String,
    val trainingScript: String,
    val bodyAdvice: String,
    val voiceAdvice: String,
    val recordingChallenge: String,
    val commonMistakes: String,
    val tipId: Int,
)

/** A focused exercise for one of the eye, body or voice training pillars. */
data class SpecializedDrill(
    val id: String,
    val category: String,
    val title: String,
    val instruction: String,
    val challenge: String,
    val safetyNotice: String? = null,
    val tipId: Int,
)

